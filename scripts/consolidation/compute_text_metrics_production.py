"""
Production-run adaptation of readability_analysis/text_metrics/compute_text_metrics.py.

Only the extraction step is changed: instead of parsing the 3 survey
comparison .txt files (8 hand-picked nodes), this reads the 9 consolidated
per-method-per-dataset JSONs (full 542-node Cora / 200-node Products eval
sets). All metric functions below (readability, halstead, entity_counts,
entity_measures, spearman/permutation helpers) are copied verbatim from the
original script -- unchanged.

Cora entity-graph matching uses only the numeric "Node N" reference pattern
(no neighbour-title data passed, same as the original script's behavior for
any node absent from neighbor_titles.json). Products entity-graph matching
uses neighbor_titles_full.json (all 200 nodes, generated by
extract_neighbor_titles_full.py -- same extraction logic as the original
4-node neighbor_titles.json, cross-checked to match on the overlapping nodes).

GSPELL/Products has two variants (embedding-projection pipeline and
text-based fallback) -- both are scored as separate "methods" since they are
saved and characterized separately.
"""
import csv
import json
import math
import os
import statistics as stats
from collections import defaultdict

import textstat

# --------------------------------------------------------------------------
# 1. Extraction (NEW -- reads consolidated JSONs instead of survey .txt files)
# --------------------------------------------------------------------------

CONSOLIDATED_DIR = "./production_run_2026-07-27/consolidated"

CORA_METHOD_FILES = {
    "GraphXAIN": "graphxain_cora.json",
    "GraphNarrator": "graphnarrator_cora.json",
    "llm-graph-cf": "llmgraphcf_cora.json",
    "GSPELL": "gspell_cora.json",
}
PRODUCTS_METHOD_FILES = {
    "GraphXAIN": "graphxain_products.json",
    "GraphNarrator": "graphnarrator_products.json",
    "llm-graph-cf": "llmgraphcf_products.json",
    "GSPELL_embedding": "gspell_products_embedding.json",
    "GSPELL_textfallback": "gspell_products_textfallback.json",
}


def extract_texts_from_consolidated(method_files):
    """Returns {node_id: {method: explanation_text}}."""
    per_method = {}
    for method, fname in method_files.items():
        with open(os.path.join(CONSOLIDATED_DIR, fname)) as f:
            per_method[method] = json.load(f)

    out = defaultdict(dict)
    for method, data in per_method.items():
        for node_id, entry in data.items():
            out[node_id][method] = entry["explanation_text"]
    return out


# --------------------------------------------------------------------------
# 2. Readability -- UNCHANGED from original script
# --------------------------------------------------------------------------

def readability(text):
    return {
        "fk_grade": textstat.flesch_kincaid_grade(text),
        "flesch_ease": textstat.flesch_reading_ease(text),
    }


# --------------------------------------------------------------------------
# 3. Halstead-style lexical complexity -- UNCHANGED from original script
# --------------------------------------------------------------------------

FUNCTION_WORDS = set("""
a an the this that these those
of in on at to from by for with without within into onto over under between among across
and or but nor so yet because although though while whereas if unless since as than
is are was were be been being am do does did doing have has had having
can could may might must shall should will would
it its they them their there here what which who whom whose when where why how
i you he she we us our your his her hers my mine ours yours theirs
not no only also very more most such same other another each any all both few many
""".split())

TOKEN_RE = __import__("re").compile(r"[a-zA-Z][a-zA-Z'\-]*")


def halstead(text):
    tokens = [t.lower() for t in TOKEN_RE.findall(text)]
    operators = [t for t in tokens if t in FUNCTION_WORDS]
    operands = [t for t in tokens if t not in FUNCTION_WORDS]
    n = len(set(operators)) + len(set(operands))
    N = len(operators) + len(operands)
    volume = N * math.log2(n) if n > 0 else 0.0
    return {
        "vocabulary_n": n,
        "length_N": N,
        "volume_V": volume,
        "volume_per_word": volume / N if N else 0.0,
    }


# --------------------------------------------------------------------------
# 4. Entity graph complexity -- UNCHANGED from original script
# --------------------------------------------------------------------------

import re  # noqa: E402

ENTITY_REF_RE = re.compile(
    r"\b(?:Node|Article|Product)[\s\-]?(\d+(?:\.\d+)*)\b|\b(ROOT)\b", re.IGNORECASE
)

GENERIC_FIRST_WORDS = {
    "new", "package", "compatible", "easy", "long", "body", "ultra", "real",
    "ultimate", "power", "focus", "green", "born", "baby",
}


def _norm(s):
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9' ]", " ", s.lower())).strip()


def _title_keys(title):
    words = _norm(title).split()
    return [" ".join(words[:k]) for k in (6, 5, 4, 3, 2) if len(words) >= k]


def _brand_word(title):
    words = _norm(title).split()
    if words and len(words[0]) >= 4 and words[0] not in GENERIC_FIRST_WORDS:
        return words[0]
    return None


def entity_counts(text, neighbours):
    """Return (S, T): distinct entities and total asserted relations."""
    mentions = defaultdict(int)

    for m in ENTITY_REF_RE.finditer(text):
        mentions["ROOT" if m.group(2) else m.group(1)] += 1

    cleaned = ENTITY_REF_RE.sub(" ", text)

    if neighbours:
        for nb in neighbours:
            nid = str(nb["node_id"])
            for _ in re.finditer(r"(?<![\d\w.])" + re.escape(nid) + r"(?![\d\w.])", cleaned):
                mentions[nid] += 1

        tnorm = _norm(cleaned)
        consumed = [False] * len(tnorm)
        candidates = []
        for nb in neighbours:
            if nb["title"] == "missing":
                continue
            for key in _title_keys(nb["title"]):
                candidates.append((len(key), 0, key, str(nb["node_id"])))
            brand = _brand_word(nb["title"])
            if brand:
                candidates.append((len(brand), 1, brand, str(nb["node_id"])))
        candidates.sort(key=lambda c: (-c[0], c[1]))

        used_brands = set()
        for _, priority, key, nid in candidates:
            if priority == 1 and key in used_brands:
                continue
            pos, hit = 0, False
            while True:
                idx = tnorm.find(key, pos)
                if idx == -1:
                    break
                end = idx + len(key)
                ok = True
                if priority == 1:
                    ok = (idx == 0 or tnorm[idx - 1] == " ") and \
                         (end >= len(tnorm) or tnorm[end] in " '")
                if ok and not any(consumed[idx:end]):
                    for i in range(idx, end):
                        consumed[i] = True
                    mentions[nid] += 1
                    hit = True
                pos = idx + 1
            if priority == 1 and hit:
                used_brands.add(key)

    return len(mentions), sum(mentions.values())


def entity_measures(text, neighbours, word_count, P=1):
    S, T = entity_counts(text, neighbours)
    c_state = S
    c_fan = T / S if S else 0.0
    c_cycle = T - S + 2 * P if S else 0
    c_density = T / (S * (S - 1)) if S > 1 else 0.0
    return {
        "S_entities": S,
        "T_relations": T,
        "C_state": c_state,
        "C_fan": c_fan,
        "C_cycle": c_cycle,
        "C_density": c_density,
        "C_state_per100w": 100 * c_state / word_count if word_count else 0.0,
        "C_cycle_per100w": 100 * c_cycle / word_count if word_count else 0.0,
    }


# --------------------------------------------------------------------------
# Main (adapted: iterates the full eval sets, per dataset, instead of the 8
# survey CASES; no human-rating correlation section, since no survey covers
# the full sets)
# --------------------------------------------------------------------------

def run_dataset(dataset_name, method_files, neighbor_titles_path, out_dir):
    texts = extract_texts_from_consolidated(method_files)

    neighbour_data = {}
    if neighbor_titles_path:
        with open(neighbor_titles_path) as f:
            neighbour_data = json.load(f)

    rows = []
    for node, methods in texts.items():
        for method, text in methods.items():
            r = readability(text)
            h = halstead(text)
            neighbours = neighbour_data.get(node, {}).get("neighbors")
            e = entity_measures(text, neighbours, h["length_N"])
            rows.append({"dataset": dataset_name, "node": node, "method": method, **r, **h, **e})

    metrics_path = os.path.join(out_dir, f"metrics_per_text_{dataset_name}.csv")
    with open(metrics_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Wrote {metrics_path} ({len(rows)} rows)")

    by_method = defaultdict(lambda: defaultdict(list))
    for r in rows:
        for k, v in r.items():
            if k not in ("dataset", "node", "method"):
                by_method[r["method"]][k].append(v)

    print(f"\n=== {dataset_name}: per-method averages over {len(texts)} eval nodes ===\n")
    print(f"{'Method':22s} {'N':>5s} {'FK':>6s} {'Ease':>7s} {'Vocab':>7s} {'Words':>7s} "
          f"{'Volume':>8s} {'V/word':>7s}")
    for m in sorted(by_method.keys()):
        a = by_method[m]
        n = len(a["fk_grade"])
        print(f"{m:22s} {n:5d} {stats.mean(a['fk_grade']):6.2f} {stats.mean(a['flesch_ease']):7.2f} "
              f"{stats.mean(a['vocabulary_n']):7.1f} {stats.mean(a['length_N']):7.1f} "
              f"{stats.mean(a['volume_V']):8.1f} {stats.mean(a['volume_per_word']):7.2f}")

    print()
    print(f"{'Method':22s} {'N':>5s} {'C_state':>8s} {'C_fan':>7s} {'C_cycle':>8s} "
          f"{'C_density':>10s} {'St/100w':>8s} {'Cy/100w':>8s}")
    for m in sorted(by_method.keys()):
        a = by_method[m]
        n = len(a["C_state"])
        print(f"{m:22s} {n:5d} {stats.mean(a['C_state']):8.2f} {stats.mean(a['C_fan']):7.2f} "
              f"{stats.mean(a['C_cycle']):8.2f} {stats.mean(a['C_density']):10.4f} "
              f"{stats.mean(a['C_state_per100w']):8.2f} {stats.mean(a['C_cycle_per100w']):8.2f}")
    print()

    return rows


def main():
    out_dir = CONSOLIDATED_DIR
    run_dataset("cora", CORA_METHOD_FILES, None, out_dir)
    run_dataset(
        "products", PRODUCTS_METHOD_FILES,
        os.path.join(CONSOLIDATED_DIR, "neighbor_titles_full.json"),
        out_dir,
    )


if __name__ == "__main__":
    main()
